// Aggregate the per-episode deliver packages into one collection package. This does not
// publish; it makes one folder a publisher can hand over: index.json, SHA256SUMS,
// collection.md, covers.html, and every episode package under its slot.
import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import {latestDelivery} from '../deliver/deliver.mjs';
import {seriesAudit, formatSeriesAudit} from './audit.mjs';

export const COLLECTION_PACKAGE_SCHEMA = 'storyweaver.collection_package.v1';

async function sha256File(file) {
  return crypto.createHash('sha256').update(await fs.readFile(file)).digest('hex');
}

async function walkFiles(dir) {
  const files = [];
  const walk = async current => {
    const entries = await fs.readdir(current, {withFileTypes: true});
    for (const entry of entries) {
      const full = path.join(current, entry.name);
      if (entry.isDirectory()) await walk(full);
      else if (entry.isFile()) files.push(full);
    }
  };
  await walk(dir);
  return files.sort();
}

function stampNow() {
  return new Date().toISOString().replace(/[:.]/g, '-');
}

function coverName(manifest) {
  const file = (manifest.files || []).find(item => /^cover.*\.png$/i.test(item.name));
  return file?.name || '';
}

export async function seriesDeliver(seriesDir, {stamp = stampNow()} = {}) {
  const audit = await seriesAudit(seriesDir);
  if (!audit.ok) {
    return {ok: false, code: 'SERIES_AUDIT_FAILED', audit, detail: formatSeriesAudit(audit)};
  }
  const collection = audit.collection;
  const missing = [];
  const episodes = [];
  for (const slot of collection.episodes) {
    const episodeDir = path.join(seriesDir, slot.slot);
    const delivery = await latestDelivery(episodeDir);
    if (!delivery.ok) {
      missing.push(`${slot.slot}: ${delivery.detail}`);
      continue;
    }
    episodes.push({slot, delivery});
  }
  if (missing.length) {
    return {ok: false, code: 'SERIES_DELIVER_INCOMPLETE', missing, detail: missing.join('\n')};
  }

  const root = path.join(seriesDir, 'deliver');
  const staging = path.join(root, `.staging-${stamp}`);
  await fs.mkdir(staging, {recursive: true});

  const index = {
    schema: COLLECTION_PACKAGE_SCHEMA,
    series: collection.series,
    created_at: new Date().toISOString(),
    episodes: [],
    credits: Boolean(audit.lock?.close?.credits),
    ai_disclosure: Boolean(audit.lock?.close?.ai_disclosure),
    checks: {audit: 'ok'},
  };

  for (const {slot, delivery} of episodes) {
    const dest = path.join(staging, slot.slot);
    await fs.cp(delivery.dir, dest, {recursive: true});
    const manifest = delivery.manifest;
    index.episodes.push({
      slot: slot.slot,
      title: slot.title || '',
      manifest: `${slot.slot}/manifest.json`,
      source: manifest.source,
      files: manifest.files.map(file => ({...file, name: `${slot.slot}/${file.name}`})),
    });
  }

  await fs.writeFile(path.join(staging, 'index.json'), `${JSON.stringify(index, null, 2)}\n`);

  const lines = [
    `# ${collection.series} · collection`,
    '',
    `${index.episodes.length} episodes. Machine package generated by \`studio series deliver\`.`,
    `AI-generated-content declaration: ${index.ai_disclosure ? 'required at upload (see the platform declaration)' : 'not recorded'}.`,
    '',
    '| slot | title | source sha256 | files |',
    '|---|---|---|---|',
  ];
  for (const episode of index.episodes) {
    lines.push(`| ${episode.slot} | ${episode.title || '(untitled)'} | ${String(episode.source?.sha256 || '').slice(0, 16)}… | ${episode.files.length} |`);
  }
  lines.push('', 'Verify `SHA256SUMS` before handing the package over. Do not publish from this folder without the platform declaration.');
  await fs.writeFile(path.join(staging, 'collection.md'), `${lines.join('\n')}\n`);

  const covers = index.episodes
    .map(episode => {
      const source = episodes.find(item => item.slot.slot === episode.slot)?.delivery.manifest;
      const name = coverName(source || {});
      return name ? `<figure><img src="${episode.slot}/${name}" alt="${episode.slot}"><figcaption>${episode.slot} ${episode.title || ''}</figcaption></figure>` : `<p>${episode.slot}: no cover file</p>`;
    })
    .join('\n');
  await fs.writeFile(path.join(staging, 'covers.html'), `<!doctype html>
<meta charset="utf-8">
<title>${collection.series} covers</title>
<style>body{font-family:sans-serif;background:#f4f1ea;color:#1b1a17;padding:24px}figure{display:inline-block;margin:0 16px 24px 0}img{width:240px;border:1px solid #ccc}figcaption{font-size:13px;margin-top:6px}</style>
${covers}
`);

  const files = await walkFiles(staging);
  const sums = [];
  for (const file of files) {
    if (path.basename(file) === 'SHA256SUMS') continue;
    const relative = path.relative(staging, file).split(path.sep).join('/');
    sums.push(`${await sha256File(file)}  ${relative}`);
  }
  await fs.writeFile(path.join(staging, 'SHA256SUMS'), `${sums.join('\n')}\n`);

  const dest = path.join(root, stamp);
  await fs.rename(staging, dest);
  await fs.writeFile(path.join(root, 'LATEST'), `${stamp}\n`);
  return {ok: true, code: 'COLLECTION_DELIVERED', dir: dest, index, files: files.length};
}

export function formatSeriesDeliver(report) {
  if (report.code === 'SERIES_AUDIT_FAILED') return `SERIES_DELIVER_BLOCKED\n${report.detail}`;
  if (report.code === 'SERIES_DELIVER_INCOMPLETE') {
    return ['SERIES_DELIVER_INCOMPLETE', ...report.missing.map(line => `- ${line}`)].join('\n');
  }
  return `COLLECTION_DELIVERED ${report.dir}\n${report.index.episodes.length} episodes, ${report.files} files\nVerify SHA256SUMS before handover.`;
}
